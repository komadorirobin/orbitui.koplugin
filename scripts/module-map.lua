-- New October 30 modules have no separate installed path: API-1 updaters are
-- already at 2,000 files. Keep exact source in this existing registry, compiled
-- lazily by the canonical loader. This explicit list also controls export-ignore.
local embedded_names = {
    "features/sui_menu_hide", "features/sui_patch_compat", "infra/sui_migrations",
    "modules/critter/book", "modules/critter/game_lines", "modules/critter/games",
    "modules/critter/menu", "modules/critter/panel_row", "modules/critter/settings",
    "modules/critter/state", "modules/critter/voice_lines", "modules/critter/voice_phrases",
    "screens/sui_bluetooth",
}
local map = {}
local files = assert(io.popen("git ls-files --cached --others --exclude-standard components/bookshelf components/simpleui"))
for path in files:lines() do
    local component, relative = path:match("^components/([^/]+)/(.+)%.lua$")
    if component then
        local root = relative:match("^([^/]+)/")
        local include = component == "bookshelf" and (root == "lib" or root == "micromodules")
            or component == "simpleui" and (root == "infra" or root == "engines"
                or root == "features" or root == "screens" or root == "modules"
                or root == "integrations" or relative == "sui_bookshelf_bridge")
        if include then
            assert(not map[relative], "Module collision: " .. relative)
            map[relative] = path
        end
    end
end
assert(files:close())
local keys = {}
for key in pairs(map) do keys[#keys + 1] = key end
table.sort(keys)
local lines = { "-- Generated by scripts/module-map.lua; do not edit by hand.", "local map = {" }
for _, key in ipairs(keys) do
    lines[#lines + 1] = string.format("    [%q] = %q,", key, map[key])
end
lines[#lines + 1] = "}"
lines[#lines + 1] = "local embedded = {"
for _, name in ipairs(embedded_names) do
    local path = assert(map[name], "Missing embedded module: " .. name)
    local f = assert(io.open(path, "rb"))
    local source = f:read("*a"); f:close()
    assert((loadstring or load)(source, "@" .. path))
    lines[#lines + 1] = string.format("    [%q] = %q,", name, source)
end
lines[#lines + 1] = "}"
-- Metadata lives outside pairs(map), preserving the established path-map API.
lines[#lines + 1] = "return setmetatable(map, { orbitui_embedded = embedded })"
local text = table.concat(lines, "\n") .. "\n"
if arg[1] == "--check" then
    local f = assert(io.open("core/orbitui_module_map.lua", "rb"))
    local existing = f:read("*a")
    f:close()
    assert(existing == text, "Regenerate core/orbitui_module_map.lua before testing or packaging")
    print("Module map: " .. #keys .. " paths verified")
else
    io.write(text)
end
