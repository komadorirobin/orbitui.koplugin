local M = {}
local function point(radius, angle)
    return 50 + radius * math.sin(angle), 50 - radius * math.cos(angle)
end

local function rosette(lobes, radius, tip)
    local path = {}
    for i = 1, lobes do
        local step = 2 * math.pi / lobes
        if i == 1 then path[1] = string.format("M%.2f %.2f", point(radius, 0)) end
        local cx, cy = point(tip, (i - .5) * step)
        local x, y = point(radius, i * step)
        path[#path + 1] = string.format("Q%.2f %.2f %.2f %.2f", cx, cy, x, y)
    end
    return '<path d="' .. table.concat(path) .. 'Z"/>'
end

