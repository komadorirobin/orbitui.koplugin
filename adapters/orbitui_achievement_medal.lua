    if item.earned and not item.secret then
        parts[#parts + 1] = string.format([[<defs>
<linearGradient id="rim" x1="0" y1="0" x2=".92" y2="1">
<stop stop-color="%s"/><stop offset=".3" stop-color="%s"/><stop offset=".47" stop-color="%s"/>
<stop offset=".64" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient>
<radialGradient id="face" gradientUnits="userSpaceOnUse" cx="40" cy="34" r="46">
<stop stop-color="%s"/><stop offset=".42" stop-color="%s"/><stop offset="1" stop-color="%s"/></radialGradient></defs>]],
            c.shadow, c.body, c.light, c.body, c.shadow, c.light, c.body, c.shadow)
        parts[#parts + 1] = '<g fill="url(#rim)">' .. rims[rarity] .. '</g>'
        if rarity == "rare" then parts[#parts + 1] = '<g fill="' .. c.light .. '" opacity=".55">' .. bead_ring .. '</g>' end
        parts[#parts + 1] = string.format([[<circle cx="50" cy="50" r="35.5" fill="url(#face)" stroke="%s" stroke-width="1.4"/>
<circle cx="50" cy="50" r="32.4" fill="none" stroke="%s" stroke-width=".7" opacity=".5"/>]], c.shadow, c.light)
        parts[#parts + 1] = symbol(glyph, c.light, 2.1, .55, 38 / 24)
        parts[#parts + 1] = symbol(glyph, c.shadow, 2.1, 0, 38 / 24)
    else
        parts[#parts + 1] = '<g fill="#ededed" stroke="#c5c5c5" stroke-width="1.2">' .. rims[rarity] .. '</g>'
        if rarity == "rare" then parts[#parts + 1] = '<g fill="#c5c5c5">' .. bead_ring .. '</g>' end
        parts[#parts + 1] = [[<defs><radialGradient id="blank" cx=".5" cy=".7" r=".65"><stop stop-color="#f5f5f5"/>
<stop offset="1" stop-color="#e4e4e4"/></radialGradient></defs>
<circle cx="50" cy="50" r="35.5" fill="url(#blank)" stroke="#c5c5c5"/>]]
        if item.secret then
            glyph = '<path d="M7 8a5 5 0 1 1 8 4c-2 1.5-3 2-3 5m0 3v.2"/>'
        end
        parts[#parts + 1] = symbol(glyph, "#777777", 1.9, 0, 1.5)
        if not item.secret and item.goal and item.goal > 0 and item.progress and item.progress > 0 then
            local fraction = math.min(1, item.progress / item.goal)
            parts[#parts + 1] = '<circle cx="50" cy="50" r="38.6" fill="none" stroke="#c5c5c5" stroke-width="3.2"/>'
            if fraction == 1 then
                parts[#parts + 1] = '<circle cx="50" cy="50" r="38.6" fill="none" stroke="' .. c.ring .. '" stroke-width="3.2"/>'
            else
                local x, y = point(38.6, fraction * 2 * math.pi)
                parts[#parts + 1] = string.format('<path d="M50 11.4A38.6 38.6 0 %d 1 %.2f %.2f" fill="none" stroke="%s" stroke-width="3.2" stroke-linecap="round"/>',
                    fraction > .5 and 1 or 0, x, y, c.ring)
            end
        end
    end
    parts[#parts + 1] = '</svg>'
    return table.concat(parts)
end

function M.widget(item, size)
    if size < 1 then return end
    local svg = M.svg(item)
    local renderer = require("ui/renderimage")
    local ok, image = pcall(renderer.renderImageData, renderer, svg, #svg, false, size, size)
    if not ok or not image then return end
    return require("ui/widget/imagewidget"):new{ image = image, width = size, height = size, alpha = true }
end
return M
